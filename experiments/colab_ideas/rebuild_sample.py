def clean(t):
    t = "".join(c for c in t if unicodedata.category(c) not in ("Cf", "Cc"))
    return " ".join(unicodedata.normalize("NFKC", t).split())


def build(out="/content/sample_480.json"):
    from datasets import load_dataset
    ds = load_dataset("google-research-datasets/nq_open")
    rows = []
    for i in IDS:
        split, idx = ("train", int(i[1:])) if i[0] == "t" else ("validation", int(i[1:]))
        row = ds[split][idx]
        rows.append({"id": f"{split}_{idx}", "question": clean(row["question"]),
                     "answers": [clean(a) for a in row["answer"]]})
    by_id = {e["id"]: e["question"] for e in rows}
    bad = [k for k, q in CHECK.items() if by_id.get(k) != q]
    json.dump(rows, open(out, "w", encoding="utf-8"), ensure_ascii=False)
    return f"{len(rows)} questions written to {out}; id/text mismatches: {bad or 'none'}"


